"""B5 scratch files: pair (a) = 12.3.c x 13.2 expressed with the LIBRARY atom table
(LexProof.Core.AtomTable) and checked two ways:

  full : analyze (atomsOf ...) over the whole product of the domains, `decide +kernel`
  proj : projConsistentT (LexProof.Verify.ProjectedCheck), `decide +kernel`

The pair is copied from eval/situation-model/gen.py (PAIR_A): same atoms, same reader
order and indices, same Cond trees, same norms. Originals are not edited.

  python gen_proj.py        # writes lean/*.lean
Run one with:  lake env lean eval/projected/lean/<file>.lean
"""
