def table(name, atoms, extra):
    rows = []
    for (nm, bands, src) in atoms:
        if bands is None:
            dom = ".bool"
        else:
            dom = ".enum [%s]" % ", ".join("⟨%s, %s⟩" % (lit(l), lit(s)) for l, s in bands)
        rows.append("  { name := %s, source := %s, domain := %s }" % (lit(nm), lit(src), dom))
    for k in range(1, extra + 1):
        rows.append("  { name := %s, source := %s, domain := .bool }" % (
            lit("X%d atom thêm" % k), lit("không có khoản nào: chỉ để nhân số điểm")))
    return "def %s : AtomTable :=\n  [\n%s\n  ]\n" % (name, ",\n".join(rows))


def readers(name, rs):
    return "def %s : List ReaderSpec :=\n  [%s]\n" % (name, ", ".join("(%s, %d, %d)" % (lit(n), a, v) for n, a, v in rs))


def norm(var, spec, mod=None):
    nid, m, act, c, ex, art = spec
    return "def %s : Norm :=\n  nrm %s .%s %s %s [%s] %s\n" % (var, lit(nid), mod or m, lit(act), c, ", ".join(ex), lit(art))


HEAD = '''import LexProof.Verify.Conflict
import LexProof.Verify.ProjectedCheck
open LexProof

/-! Scratch file, not part of the library. Pair (a) = 12.3.c x 13.2 over the library
atom table. Generated by eval/projected/gen_proj.py. -/

def nrm (id : String) (m : Modality) (act : String) (c : Cond) (ex : List Cond)
    (art : String) : Norm :=
  { id := id, modality := m, act := act, condition := c, exceptions := ex
  , priority := none
  , source := { docId := "44/2019/QH14", docType := .law
              , effective := ⟨2020, 1, 1⟩, article := art }
  , references := [] }

def catalog : List String := []
'''


def gen(kind, extra, opp):
    L = [HEAD, table("tS", ATOMS_S, extra), table("tP", ATOMS_P, 0),
         readers("rS", READERS_S), readers("rP", READERS_P),
         norm("nA", N_12_3_C), norm("nB", N_13_2, "obligation" if opp else None),
         "def norms : List Norm := [nA, nB]\n"]
    if kind == "full":
        res = "false" if opp else "true"
        L.append("theorem full : (analyze (atomsOf tS tP rS rP) catalog norms).isConsistentOn = %s := by\n  decide +kernel\n\n#print axioms full\n" % res)
    elif kind == "proj":
        L.append("""theorem tableS_ok : tableFindings tS = [] := by decide
theorem tableP_ok : tableFindings tP = [] := by decide
theorem readersS_ok : readerFindings tS rS = [] := by decide
theorem readersP_ok : readerFindings tP rP = [] := by decide

theorem card_pos : 0 < Finite.card (Valuation tS) := card_pos_of_tableFindings tableS_ok
""")
        if not opp:
            L.append("""theorem proj : projConsistentT tS tP rS rP nA nB = true := by decide +kernel

theorem no_conflict_anywhere : ∀ (π : Valuation tP) (s : Valuation tS),
    ¬ Conflict (atomsOf tS tP rS rP) nA nB π s := fun π s =>
  not_conflict_of_projConsistentT
    (readerAtomsOk_of_readersOk (readersOk_of_readerFindings readersS_ok))
    (readerAtomsOk_of_readersOk (readersOk_of_readerFindings readersP_ok)) nA nB proj π s

theorem enumerated : projPoints tS tP rS rP nA nB = 1536 := by decide
theorem full_product : tS.points * tP.points = 1536 * %d := by decide

#print axioms proj
#print axioms no_conflict_anywhere
#print axioms enumerated
""" % (2 ** extra))
        else:
            L.append("""theorem proj : projConsistentT tS tP rS rP nA nB = false := by decide +kernel

theorem real_conflict : ∃ (π : Valuation tP) (s : Valuation tS),
    (atomsOf tS tP rS rP).valid π s = true ∧ Conflict (atomsOf tS tP rS rP) nA nB π s :=
  exists_conflict_of_not_projConsistentT (nonEmpty_of_tableFindings tableS_ok)
    (nonEmpty_of_tableFindings tableP_ok) nA nB proj

#print axioms proj
#print axioms real_conflict
""")
    return "\n".join(L)


def main():
    os.makedirs(OUT, exist_ok=True)
    for extra in (0, 1, 2, 3):
        for kind in ("full", "proj"):
            with open(os.path.join(OUT, "PairA_%s_x%d.lean" % (kind, extra)), "w", encoding="utf-8", newline="\n") as f:
                f.write(gen(kind, extra, False))
    for kind in ("full", "proj"):
        with open(os.path.join(OUT, "PairA_%s_opp.lean" % kind), "w", encoding="utf-8", newline="\n") as f:
            f.write(gen(kind, 0, True))


if __name__ == "__main__":
    main()
